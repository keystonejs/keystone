import { expect, test } from 'vitest'
import { config, list } from '@keystone-6/core'
import {
  buildArtifacts,
  createSystem,
} from '@keystone-6/core/___internal-do-not-use-will-break-in-patch/artifacts'
import { allowAll } from '@keystone-6/core/access'
import { checkbox, relationship, select, text } from '@keystone-6/core/fields'
import { setupTestEnv } from './test-runner.ts'
import { dbProvider, getPrismaSchema } from './utils.ts'

test('isIndexed: true and db.map on a text field generates a valid Prisma schema', async () => {
  const { artifacts, config } = await setupTestEnv({
    lists: {
      Test: list({
        access: allowAll,
        fields: {
          somethingIndexed: text({ isIndexed: true, db: { map: 'something' } }),
          other: text(),
        },
      }),
    },
  })

  expect(artifacts.prisma).toEqual(
    `// This file is automatically generated by Keystone, do not modify it manually.
// Modify your Keystone config when you want to change this.

datasource ${dbProvider} {
  provider = "${dbProvider}"
}

generator client {
  provider = "prisma-client"
  output   = "${config.db.prismaClientPath}"
}

model Test {
  id               String @id @default(cuid())
  somethingIndexed String @default("") @map("something")
  other            String @default("")

  @@index([somethingIndexed])
}
`
  )
})

